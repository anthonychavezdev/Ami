func TestHealthAndOrigins(t *testing.T) {
	ts := newTestServer(t, false)
	r := ts.get("/api/health", "")
	ts.check("health", r.status == 200 && r.obj().str("status") == "ok", r)
	h := r.header
	ts.check("security headers", h.Get("X-Content-Type-Options") == "nosniff" && h.Get("Cache-Control") == "no-store", h)
	ts.check("hardening headers", h.Get("X-Frame-Options") == "DENY" && strings.Contains(h.Get("Content-Security-Policy"), "default-src 'none'") &&
		strings.Contains(h.Get("Permissions-Policy"), "camera=()") && h.Get("Cross-Origin-Opener-Policy") == "same-origin", h)

	r = ts.do("OPTIONS", "/api/posts", nil, "", "Origin", "http://good.example", "Access-Control-Request-Method", "POST")
	ts.check("preflight from allowed origin", r.status == 204 && r.header.Get("Access-Control-Allow-Origin") == "http://good.example" && r.header.Get("Access-Control-Max-Age") == "600", r.status, r.header)
	r = ts.do("OPTIONS", "/api/posts", nil, "", "Origin", "http://evil.example", "Access-Control-Request-Method", "POST")
	ts.check("preflight from other origin -> 403", r.status == 403, r)
	r = ts.do("GET", "/api/health", nil, "", "Origin", "http://evil.example")
	ts.check("no CORS headers for other origins", r.status == 200 && r.header.Get("Access-Control-Allow-Origin") == "" && strings.Contains(r.header.Get("Vary"), "Origin"), r.header)
	r = ts.do("GET", "/api/health", nil, "", "Origin", ts.url)
	ts.check("the page's own origin is allowed", r.header.Get("Access-Control-Allow-Origin") == ts.url, r.header)
}

